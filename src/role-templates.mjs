/**
 * 根据岗位标题与 JD 文本自动匹配最相关的内置全行业岗位模板
 */
export function detectRoleTemplate(title = '', jdText = '') {
  const hay = `${title} ${jdText}`.toLowerCase();
  let best = ROLE_TEMPLATES[ROLE_TEMPLATES.length - 1];
  let bestHits = 0;

  for (const tpl of ROLE_TEMPLATES) {
    let hits = 0;
    for (const kw of tpl.keywords) {
      if (hay.includes(kw.toLowerCase())) {
        hits += String(title).toLowerCase().includes(kw.toLowerCase()) ? 3 : 1;
      }
    }
    if (hits > bestHits) {
      bestHits = hits;
      best = tpl;
    }
  }
  return best;
}

export function getRoleTemplateById(templateId) {
  return ROLE_TEMPLATES.find((t) => t.id === templateId) || ROLE_TEMPLATES[ROLE_TEMPLATES.length - 1];
}

/**
 * 获取指定岗位模板的完整深度面试题库（行业专属核心题 + 行业扩充硬核题 + 全职场必考通用题，自动去重，每岗 14~16 道）
 */
export function getFullQuestionsForTemplate(templateId) {
  const tpl = getRoleTemplateById(templateId);
  const merged = [
    ...(tpl.questions || []),
    ...(EXTRA_QUESTIONS_BY_TEMPLATE[tpl.id] || []),
    ...UNIVERSAL_INTERVIEW_QUESTIONS,
  ];
  const seen = new Set();
  const result = [];
  for (const q of merged) {
    if (!q || !q.question) continue;
    const key = String(q.question).trim();
    if (seen.has(key)) continue;
    seen.add(key);
    result.push(q);
  }
  return result;
}

/**
 * 组装指定岗位类型的 6 维度面试者反向考察清单（通用 5 维 + 岗位专属第 6 维）
 */
export function buildFullReverseChecklist(templateId) {
  const tpl = getRoleTemplateById(templateId);
  const checklist = UNIVERSAL_REVERSE_CHECKLIST.map((group) => ({
    dimension: group.dimension,
    items: group.items,
  }));
  if (tpl.roleSpecificReverse?.length) {
    checklist.push({
      dimension: `6. 「${tpl.name}」专属必问核验项`,
      items: tpl.roleSpecificReverse,
    });
  }
  return checklist;
}
